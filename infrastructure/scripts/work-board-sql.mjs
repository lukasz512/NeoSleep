// Turns slimmed Linear issues (linear-slim.mjs) into one idempotent SQL file for a
// reviewed migration (CORE-184): the shared Supabase DB holds production data, so the
// work board's history lands through a PR, not an ad-hoc script run.
//
// Every statement is safe to repeat: an item already on the board (same KEY-n or the
// same linear_identifier) is skipped together with its events, and team counters only
// move forward.

/** A SQL literal; strings use '' doubling (standard_conforming_strings is on). */
export function lit(value) {
  if (value === null || value === undefined) return "NULL";
  if (typeof value === "number") {
    if (!Number.isFinite(value)) throw new Error(`not a finite number: ${value}`);
    return String(value);
  }
  return `'${String(value).replace(/\u0000/g, "").replace(/'/g, "''")}'`;
}

function textArray(values) {
  return values.length ? `ARRAY[${values.map(lit).join(", ")}]::text[]` : "'{}'::text[]";
}

function itemStatement({ item, comments }) {
  const ts = (v) => (v ? `${lit(v)}::timestamptz` : "NULL");
  const finished = item.completed_at ?? item.created_at;
  const events = [
    `SELECT id, 'created', ${lit(item.status)}, ${lit(`Imported from Linear ${item.linear_identifier}`)}, 'linear', 'import', ${ts(item.created_at)} FROM ins`,
    ...comments.map((c) => `SELECT id, 'comment', NULL, ${lit(c.body)}, 'linear', 'import', ${ts(c.created_at)} FROM ins`),
  ];
  return `WITH ins AS (
  INSERT INTO platform.work_item
    (team_key, number, title, problem, change, done_when, status, priority, labels, links, branch,
     source, linear_identifier, created_by, created_at, updated_at, status_changed_at, completed_at)
  VALUES (${lit(item.team_key)}, ${lit(item.number)}, ${lit(item.title)}, ${lit(item.problem)}, ${lit(item.change)},
    ${lit(item.done_when)}, ${lit(item.status)}, ${lit(item.priority)}, ${textArray(item.labels)},
    ${lit(JSON.stringify(item.links))}::jsonb, NULL, 'linear_import', ${lit(item.linear_identifier)}, 'linear',
    ${ts(item.created_at)}, ${ts(finished)}, ${ts(finished)}, ${ts(item.completed_at)})
  ON CONFLICT DO NOTHING
  RETURNING id
)
INSERT INTO platform.work_item_event (item_id, kind, to_status, body, actor, actor_kind, created_at)
${events.join("\nUNION ALL ")};`;
}

/** The whole migration body: teams, items with their events, then the counters. */
export function buildImportSql(slim, { exportedAt }) {
  const teams = [...new Set(slim.map((s) => s.item.team_key))].sort();
  const parts = [
    "-- =============================================================================",
    "-- Work board history from Linear, slimmed (CORE-184; board: CORE-177, decision K3).",
    "-- Platform schema only. Idempotent: items already on the board are skipped with",
    "-- their events, team counters only move forward.",
    "-- ROLLBACK (manual): DELETE FROM platform.work_item WHERE source = 'linear_import';",
    "-- =============================================================================",
    `-- Generated by infrastructure/scripts/work-board-import.mjs --sql from the Linear export of ${exportedAt}.`,
    `-- ${slim.length} items, ${slim.reduce((n, s) => n + s.comments.length, 0)} kept comments. Do not edit by hand; regenerate.`,
    "",
    ...teams.map((key) => `INSERT INTO platform.work_team (key, name, kind) VALUES (${lit(key)}, ${lit(key)}, 'client') ON CONFLICT (key) DO NOTHING;`),
    "",
    ...[...slim].sort((a, b) => a.item.team_key.localeCompare(b.item.team_key) || a.item.number - b.item.number).map(itemStatement),
    "",
    `UPDATE platform.work_team t SET next_number = GREATEST(t.next_number, m.max_number + 1)
  FROM (SELECT team_key, max(number) AS max_number FROM platform.work_item GROUP BY team_key) m
 WHERE m.team_key = t.key;`,
    "",
  ];
  return parts.join("\n");
}
